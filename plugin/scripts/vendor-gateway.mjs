/**
 * Copy the Python gateway into the npm package directory before `npm pack`.
 *
 * npm cannot pack files outside `plugin/`, but a user who installs the plugin
 * from npm has no sibling `gateway/` checkout. The installer's
 * `gatewaySourceDir()` looks for `plugin/gateway` first, so vendoring the
 * Python source there makes a published install self-contained.
 *
 * `postpack` removes the generated directory so local development continues
 * to use the live `../gateway` checkout.
 */

import { cpSync, existsSync, mkdirSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const dest = path.resolve(here, "..", "gateway");

if (process.argv.includes("--clean")) {
  rmSync(dest, { recursive: true, force: true });
  process.exit(0);
}

const source = path.resolve(here, "..", "..", "gateway");
const packageRoot = path.join("src", "onemin_gateway");
for (const required of ["pyproject.toml", "README.md", packageRoot]) {
  if (!existsSync(path.join(source, required))) {
    throw new Error(`Cannot vendor gateway: missing ${path.join(source, required)}`);
  }
}

rmSync(dest, { recursive: true, force: true });
mkdirSync(dest, { recursive: true });
for (const entry of ["pyproject.toml", "README.md", "config.sample.json"]) {
  const from = path.join(source, entry);
  if (existsSync(from)) {
    cpSync(from, path.join(dest, entry));
  }
}
mkdirSync(path.join(dest, "src", "onemin_gateway"), { recursive: true });
for (const entry of readdirSync(path.join(source, packageRoot))) {
  if (entry.endsWith(".py")) {
    cpSync(
      path.join(source, packageRoot, entry),
      path.join(dest, packageRoot, entry),
    );
  }
}
writeFileSync(path.join(dest, ".vendored-by-prepack"), "Generated by plugin/scripts/vendor-gateway.mjs\n");
